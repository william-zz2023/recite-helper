const assert = require('node:assert/strict');
const test = require('node:test');
const fs = require('node:fs');
const path = require('node:path');

process.env.TZ = 'Asia/Shanghai';
let createStudyStore, recordPracticeResult;
test.before(async () => {
  ({ createStudyStore } = await import('../src/services/study-history.js'));
  ({ recordPracticeResult } = await import('../src/services/practice.js'));
});
const KEY = 'recite-helper.music-overview.study.v1';
const question = { id: 0, src: '音乐美学', ch: '音乐美学' };

function setup({ storage = new Map(), now = '2026-10-19T10:00:00+08:00', readFails = false } = {}) {
  let instant = now, writeFails = false;
  const messages = [], state = { screen: 'history', mode: 'qa', results: [] };
  const store = createStudyStore({
    now: () => new Date(instant),
    storage: () => ({
      getItem(key) { if (readFails) throw Error('Storage unavailable'); return storage.get(key) ?? null; },
      setItem(key, value) { if (writeFails) throw Error('Quota exceeded'); storage.set(key, value); }
    }),
  });
  return {
    store, state, storage, messages,
    at(value) { instant = value; }, failWrites(value) { writeFails = value; },
    add(kind, score = 0, ok = false) { store.record(question, kind, { score, ok }); },
    summary(day = '2026-10-19') { return store.summary(day); },
    snapshot() { return structuredClone(store.history); },
    async import(value) {
      try { store.importBackup(typeof value === 'string' ? JSON.parse(value) : value); }
      catch (error) { messages.push('未导入：' + error.message); }
    },
  };
}

test('opening the page alone does not create a check-in', () => {
  const env = setup();
  assert.equal(env.summary().total, 0);
  assert.equal(env.storage.has(KEY), false);
  assert.equal(env.store.streak(), 0);
});

test('attempts accumulate while the number of studied questions is deduplicated', () => {
  const env = setup();
  env.add('qa', 0.6, false); env.add('qa', 0.9, true); env.add('full', 0.75, false);
  env.add('read'); env.add('read'); env.add('listen'); env.add('listen');
  const summary = env.summary(), item = summary.items[0];
  assert.equal(summary.total, 1);
  assert.equal(summary.practiced, 1);
  assert.equal(summary.read, 1);
  assert.equal(summary.listen, 1);
  assert.equal(summary.attempts, 3);
  assert.equal(summary.passed, 1);
  assert.equal(item.activities.qa.count, 2);
  assert.equal(item.activities.qa.lastScore, 90);
  assert.equal(item.activities.read.count, 1);
  assert.equal(item.activities.listen.count, 2);
});

test('records survive a page reload using the same browser storage', () => {
  const env = setup(); env.add('full', 0.88, true);
  const reloaded = setup({ storage: env.storage });
  assert.deepEqual(reloaded.snapshot(), env.snapshot());
  assert.equal(reloaded.summary().items[0].title, question.src);
  assert.equal(reloaded.summary().items[0].activities.full.lastScore, 88);
});

test('records generated by the original single-file app load and merge under the same key', () => {
  const legacy = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/legacy-study-v1.json'), 'utf8'));
  const storage = new Map([[KEY, JSON.stringify(legacy)]]);
  const env = setup({ storage, now: '2026-10-20T18:00:00+08:00' });
  assert.deepEqual(env.snapshot(), legacy);
  env.add('read');
  env.store.importBackup(legacy);
  assert.equal(env.summary('2026-10-20').attempts, 1);
  assert.equal(env.summary('2026-10-20').read, 1);
  assert.equal(env.summary('2026-10-20').items[0].activities.qa.lastScore, 88);
  assert.equal(env.store.exportBackup().version, 1);
});

test('crossing local midnight creates two days even when both events share a UTC date', () => {
  const env = setup({ now: '2026-10-19T23:59:00+08:00' }); env.add('qa', 1, true);
  env.at('2026-10-20T00:01:00+08:00'); env.add('qa', 0.7, false);
  assert.equal(env.summary('2026-10-19').attempts, 1);
  assert.equal(env.summary('2026-10-20').attempts, 1);
  assert.equal(env.store.streak(), 2);
});

test('streaks cross month and year boundaries and reset after a missed day', () => {
  const env = setup({ now: '2026-12-31T21:00:00+08:00' }); env.add('read');
  env.at('2027-01-01T09:00:00+08:00'); env.add('read');
  assert.equal(env.store.streak(), 2);
  env.at('2027-01-02T09:00:00+08:00'); assert.equal(env.store.streak(), 2);
  env.at('2027-01-03T09:00:00+08:00'); assert.equal(env.store.streak(), 0);
  assert.equal(env.store.shiftDate('2028-03-01', -1), '2028-02-29');
});

test('practice submissions record their real mode, score, and result', () => {
  const env = setup();
  env.state.mode = 'full';
  recordPracticeResult(env.state, env.store, question, 0.82, true);
  assert.equal(env.state.results.length, 1);
  assert.equal(env.summary().items[0].activities.full.lastScore, 82);
  assert.equal(env.summary().items[0].activities.full.passed, 1);
  assert.equal(env.summary().items[0].activities.qa, undefined);
});

test('reimporting the same backup is idempotent and keeps the newer score', async () => {
  const env = setup(); env.add('qa', 0.6, false);
  const old = env.snapshot();
  env.at('2026-10-19T11:00:00+08:00'); env.add('qa', 0.95, true);
  await env.import(old); await env.import(old);
  assert.equal(env.summary().attempts, 2);
  assert.equal(env.summary().items[0].activities.qa.lastScore, 95);
  assert.equal(env.summary().passed, 1);
});

test('import merges other dates and questions without erasing existing records', async () => {
  const env = setup(); env.add('read');
  const other = setup({ now: '2026-10-18T09:00:00+08:00' }); other.add('full', 0.9, true);
  await env.import(other.snapshot());
  assert.equal(env.summary('2026-10-19').read, 1);
  assert.equal(env.summary('2026-10-18').practiced, 1);
  assert.equal(Object.keys(env.snapshot().days).length, 2);
});

test('invalid backups are rejected without replacing working records', async () => {
  const env = setup(); env.add('qa', 1, true);
  const original = env.snapshot();
  const invalid = [
    '{invalid json', { version: 2, days: {} },
    { version: 1, days: { '2026-02-30': { items: {} } } },
    JSON.parse('{"version":1,"days":{"__proto__":{"items":{}}}}')
  ];
  const negative = structuredClone(original); negative.days['2026-10-19'].items['0'].activities.qa.count = -1; invalid.push(negative);
  const excessivePasses = structuredClone(original); excessivePasses.days['2026-10-19'].items['0'].activities.qa.passed = 2; invalid.push(excessivePasses);
  const invalidKind = structuredClone(original); invalidKind.days['2026-10-19'].items['0'].activities.constructor = { count: 1, lastAt: new Date().toISOString() }; invalid.push(invalidKind);
  for (const backup of invalid) {
    await env.import(backup);
    assert.deepEqual(env.snapshot(), original);
    assert.match(env.messages.at(-1), /未导入/);
  }
});

test('quota failure keeps in-memory records and reports that they are unsaved', () => {
  const env = setup(); env.failWrites(true); env.add('qa', 0.6, false);
  assert.equal(env.summary().attempts, 1);
  assert.equal(env.storage.has(KEY), false);
  assert.match(env.store.error, /未能保存/);
  env.failWrites(false); env.add('qa', 0.9, true);
  assert.equal(env.store.error, '');
  assert.equal(setup({ storage: env.storage }).summary().attempts, 2);
});

test('unreadable old storage is preserved rather than silently overwritten', () => {
  const storage = new Map([[KEY, '{broken original data']]);
  const env = setup({ storage }); env.add('read');
  assert.equal(env.summary().read, 1);
  assert.equal(storage.get(KEY), '{broken original data');
  assert.equal(env.store.unreadableOriginal, '{broken original data');
  assert.equal(env.store.exportBackup().unreadableOriginal, '{broken original data');
  assert.match(env.store.error, /原有记录无法读取/);
});

test('unavailable storage does not prevent study activity in the current page', () => {
  const env = setup({ readFails: true }); env.add('read');
  assert.equal(env.summary().read, 1);
});
